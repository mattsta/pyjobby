class RenderReport(Job):
    """A per-step budget: the step that hangs is the one that is blamed."""

    step_timeout = 5  # default budget for every step in this job

    async def task(self) -> dict[str, Any]:
        rows = await self.step("gather", self.gather)
        return await self.step("render", self.render, rows, timeout=0.2)

    async def gather(self) -> list[int]:
        return [1, 2, 3]

    async def render(self, rows: list[int]) -> dict[str, Any]:
        await asyncio.sleep(5)  # hangs, far past this step's 0.2s
        return {"rows": len(rows)}


class Impatient(Job):
    """A job-level ceiling: this job may never run longer than a second."""

    timeout = 1

    async def task(self) -> str:
        await asyncio.sleep(30)
        return "never"


async def test_a_blown_step_budget_is_recorded_against_that_step(
    client, live_worker, unique_queue
):
    await live_worker()

    job_id = await client.enqueue(
        "tests.test_writing_jobs.RenderReport",
        queue=unique_queue,
        max_retries=1,  # no retry: go straight to the dead-letter state
        initial_retry_delay=0,
    )

    row = await wait_for_job_state(client.pool, job_id, ("crashed",), timeout=20)
    assert "step 'render' exceeded its 0.2s timeout" in row["error_message"]

    steps = await client.pool.fetch(
        """SELECT step_seq, name, output, error FROM jorb_step
            WHERE job_id=$1 ORDER BY step_seq""",
        job_id,
    )
    assert steps[0]["name"] == "gather"
    assert steps[0]["output"] == [1, 2, 3]  # the completed prefix stands
    assert steps[1]["name"] == "render"
    assert steps[1]["error"].startswith("StepTimeoutError:")


