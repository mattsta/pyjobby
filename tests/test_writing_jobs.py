class PollShipment(Job):
    """Publishes where it is, sleeps durably, then finishes."""

    async def task(self, order_id: int) -> dict[str, Any]:
        await self.set_event("stage", {"at": "awaiting-carrier"})
        await self.sleep(1)
        return {"order": order_id, "stage": "delivered"}


async def test_a_durable_sleep_holds_no_worker(client, live_worker, unique_queue):
    await live_worker()

    job_id = await client.enqueue(
        "tests.test_writing_jobs.PollShipment", queue=unique_queue, order_id=7
    )

    # while it sleeps the job is back in the queue with a future run_after —
    # it occupies no worker and no connection
    for _ in range(50):
        row = await client.pool.fetchrow(
            "SELECT state, run_after > now() AS future FROM jorb WHERE id=$1", job_id
        )
        if row["state"] == "queued" and row["future"]:
            break
        await asyncio.sleep(0.1)
    assert row["state"] == "queued" and row["future"], dict(row)
    assert await client.get_event(job_id, "stage", timeout=5) == {
        "at": "awaiting-carrier"
    }

    row = await wait_for_job_state(client.pool, job_id, ("finished",), timeout=15)
    assert row["result"] == {"order": 7, "stage": "delivered"}


