class WaitForApproval(Job):
    """Announces itself, then blocks on its mailbox until someone decides."""

    async def task(self, order_id: int, timeout: float = 20) -> dict[str, Any]:
        await self.set_event("awaiting", {"order": order_id})
        decision = await self.recv(topic="approval", timeout=timeout)
        return {"approved": bool(decision and decision.get("ok"))}


class Approve(Job):
    """Delivers the decision to another job's mailbox."""

    async def task(self, dest: int) -> str:
        await self.send(dest, {"ok": True}, topic="approval")
        return "sent"


async def test_one_job_unblocks_another(client, live_worker, unique_queue):
    await live_worker()
    await live_worker()  # second worker: the approver must not queue behind the waiter

    waiter = await client.enqueue(
        "tests.test_writing_jobs.WaitForApproval", queue=unique_queue, order_id=99
    )
    assert await client.get_event(waiter, "awaiting", timeout=10) == {"order": 99}

    approver = await client.enqueue(
        "tests.test_writing_jobs.Approve", queue=unique_queue, dest=waiter
    )
    await wait_for_job_state(client.pool, approver, ("finished",))

    row = await wait_for_job_state(client.pool, waiter, ("finished",), timeout=25)
    assert row["result"] == {"approved": True}


async def test_an_operator_can_deliver_the_same_message(
    client, live_worker, unique_queue
):
    """`recv()` does not care who sent it: the client can too."""
    await live_worker()

    waiter = await client.enqueue(
        "tests.test_writing_jobs.WaitForApproval", queue=unique_queue, order_id=100
    )
    await client.get_event(waiter, "awaiting", timeout=10)
