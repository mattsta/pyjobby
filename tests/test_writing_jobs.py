"""Executable proof for every example in ``docs/writing-jobs.md``.

The job classes below are the guide's examples, verbatim: the document is
written from this file, not beside it. Each test enqueues one of them and
drives a REAL worker (the ``live_worker`` fixture), so an API change breaks
the guide here instead of leaving it quietly wrong.

The workers run in this process, which is why a plain module-level list is
enough to observe "did that step really execute again?" — the job code and
the assertion share one interpreter. ``guide_payment`` is the little
application table the ``transaction()`` example writes to; it is created on
demand here and belongs to this file, not to the schema.
"""

