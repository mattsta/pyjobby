class RecordPayment(Job):
    """The write and its checkpoint are one commit, so neither can be lost."""

    async def task(self, order_id: int, cents: int) -> dict[str, Any]:
        return await self.transaction("record", self.record, order_id, cents)

    async def record(self, conn: Any, order_id: int, cents: int) -> dict[str, Any]:
        await conn.execute(
            "INSERT INTO guide_payment (order_id, cents) VALUES ($1, $2)",
            order_id,
            cents,
        )
        if self.job["error_count"] == 0:
            # a crash here rolls the INSERT back with the checkpoint
            raise RuntimeError("crashed after the write, before the commit")
        return {"order": order_id, "cents": cents}


async def test_a_transaction_writes_exactly_once(
    client, live_worker, unique_queue, payments_table
):
    await live_worker()

    order_id = int(time.time() * 1000) % 1_000_000_000
    job_id = await client.enqueue(
        "tests.test_writing_jobs.RecordPayment",
        queue=unique_queue,
        max_retries=3,
        initial_retry_delay=0,
        order_id=order_id,
        cents=1999,
    )

    row = await wait_for_job_state(client.pool, job_id, ("finished",))
    assert row["result"] == {"order": order_id, "cents": 1999}
    assert row["error_count"] == 1  # the first attempt wrote, then raised

    # the rolled-back write left nothing: exactly one row, not two
    written = await client.pool.fetch(
        "SELECT cents FROM guide_payment WHERE order_id = $1", order_id
    )
    assert [r["cents"] for r in written] == [1999]


