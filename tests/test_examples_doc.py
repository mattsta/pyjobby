async def test_a_schedule_needs_a_connection_with_the_json_codecs(db_params, batch_ref):
    """Why the docs say ``pyjobby.db.connect``, not ``asyncpg.connect``.

    ``jorb_schedule.kwargs`` is JSONB. A bare asyncpg connection has no codec
    for it, so passing a dict fails at the INSERT -- the same trap that once
    made ``JobClient.enqueue()`` fail in production against a pool built
    without them.
    """
    from pyjobby import db as pyjobby_db
    from pyjobby.admin_api import AdminAPI

    bare = await asyncpg.connect(**db_params)
    try:
        with pytest.raises(asyncpg.DataError):
            await AdminAPI(bare).create_schedule(
                name=f"bare-{batch_ref}",
                job_class="tests.test_examples_doc.DailyRevenueReport",
                cron_expr="0 2 * * *",
                kwargs={"region": "emea"},
            )
    finally:
        await bare.close()

    equipped = await pyjobby_db.connect(**db_params)
    try:
        api = AdminAPI(equipped)
        schedule = await api.create_schedule(
            name=f"equipped-{batch_ref}",
            job_class="tests.test_examples_doc.DailyRevenueReport",
            cron_expr="0 2 * * *",
            kwargs={"region": "emea"},
        )
        assert schedule["kwargs"] == {"region": "emea"}
        # this connection is outside the test's transaction, so the row it
        # committed has to be removed by hand
        await api.delete_schedule(schedule["id"])
    finally:
        await equipped.close()
