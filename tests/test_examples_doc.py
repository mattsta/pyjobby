class AwaitRefundApproval(Job):
    """Publishes what it needs, then blocks on its mailbox."""

    async def task(self, ref: str, timeout: float = 25) -> dict[str, Any]:
        await self.set_event("awaiting", {"ref": ref})
        decision = await self.recv(topic="refund", timeout=timeout)
        return {"ref": ref, "approved": bool(decision and decision.get("ok"))}


async def test_an_operator_approves_a_waiting_job(
    client, live_worker, unique_queue, batch_ref
):
    await live_worker()

    job_id = await client.enqueue(
        "tests.test_examples_doc.AwaitRefundApproval",
        queue=unique_queue,
        tags={"ref": batch_ref, "needs": "approval"},
        ref=batch_ref,
    )

    # a dashboard finds it by tag, and reads what it is waiting for
    found = await client.search_jobs(tags={"needs": "approval"})
    assert job_id in [j["id"] for j in found]
    assert await client.get_event(job_id, "awaiting", timeout=10) == {"ref": batch_ref}

    await client.send_message(job_id, {"ok": True}, topic="refund")

    row = await wait_for_job_state(client.pool, job_id, ("finished",), timeout=30)
    assert row["result"] == {"ref": batch_ref, "approved": True}


