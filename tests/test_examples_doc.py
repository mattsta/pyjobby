# ===========================================================================


class ProcessUpload(Job):
    """Parse an uploaded batch once, then record it exactly once.

    The parse is a ``step()`` because re-parsing on a retry is waste; the
    write is a ``transaction()`` because a retry that wrote twice would
    double the batch.
    """

    async def task(self, batch: str, raw: list[str]) -> dict[str, Any]:
        rows = await self.step("parse", self.parse, raw)
        await self.transaction("store", self.store, batch, rows)
        return {"batch": batch, "rows": len(rows)}

    def parse(self, raw: list[str]) -> list[dict[str, Any]]:
        FETCHES.append(len(raw))  # the expensive work, counted
        return [
            {"sku": sku, "units": int(units)}
            for sku, units in (line.split(",") for line in raw)
        ]

    async def store(
        self, conn: Any, batch: str, rows: list[dict[str, Any]]
    ) -> list[int]:
        written = []
        for row in rows:
            written.append(
                await conn.fetchval(
                    "INSERT INTO example_row (batch, sku, units) "
                    "VALUES ($1, $2, $3) RETURNING id",
                    batch,
                    row["sku"],
                    row["units"],
                )
            )
        if self.job["error_count"] == 0:
            # a crash here rolls the whole INSERT set back with the checkpoint
            raise RuntimeError("crashed before the commit")
        return written


async def test_the_upload_job_parses_once_and_writes_once(
    client, live_worker, unique_queue, app_tables, batch_ref
):
    FETCHES.clear()
    await live_worker()

    job_id = await client.enqueue(
        "tests.test_examples_doc.ProcessUpload",
        queue=unique_queue,
        max_retries=3,
        initial_retry_delay=0,
        batch=batch_ref,
        raw=["a-1,2", "b-2,5"],
    )

    row = await wait_for_job_state(client.pool, job_id, ("finished",), timeout=20)
    assert row["result"] == {"batch": batch_ref, "rows": 2}
    assert row["error_count"] == 1  # the first attempt wrote, then raised
    assert FETCHES == [2]  # ...but the parse still ran exactly once

    written = await client.pool.fetch(
        "SELECT sku, units FROM example_row WHERE batch = $1 ORDER BY sku", batch_ref
    )
    assert [(r["sku"], r["units"]) for r in written] == [("a-1", 2), ("b-2", 5)]


async def test_a_deadline_key_refuses_the_duplicate_request(
    client, unique_queue, batch_ref
):
    """The idempotency key a web handler builds from the request."""
    key = f"upload:{batch_ref}"

    first = await client.enqueue(
        "tests.test_examples_doc.ProcessUpload",
        queue=unique_queue,
        deadline_key=key,
        batch=batch_ref,
        raw=["a-1,2"],
    )
    assert first > 0

    with pytest.raises(asyncpg.UniqueViolationError):
        await client.enqueue(
            "tests.test_examples_doc.ProcessUpload",
            queue=unique_queue,
            deadline_key=key,
            batch=batch_ref,
            raw=["a-1,2"],
        )

    # the index is on (deadline_key, queue) WHERE state = 'queued', so the
    # same key in another queue is a different job...
    other = await client.enqueue(
        "tests.test_examples_doc.ProcessUpload",
        queue=f"{unique_queue}-other",
        deadline_key=key,
        batch=batch_ref,
        raw=["a-1,2"],
    )
    assert other != first

    # ...and once the first job leaves `queued` the key is free again: this
    # deduplicates concurrent submissions, it does not remember forever
    await client.pool.execute("UPDATE jorb SET state = 'finished' WHERE id = $1", first)
    again = await client.enqueue(
        "tests.test_examples_doc.ProcessUpload",
        queue=unique_queue,
        deadline_key=key,
        batch=batch_ref,
        raw=["a-1,2"],
    )
    assert again not in (first, other)


