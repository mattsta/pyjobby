# 5. A rate-limited third-party API
# ===========================================================================


class ChargeCards(Job):
    """Paces its calls to a rate-limited provider, one per second.

    The pause is ``self.sleep()``, so the job leaves the worker between
    calls instead of holding one for the whole run. Each charge is a
    ``step()``, so the retry after a provider error re-sends only the one
    that failed — and it still carries an idempotency key, because
    ``step()`` is at-least-once for anything outside this database.

    The loop is deterministic: its length comes from ``refs``, a checkpointed
    argument, so every attempt makes the same sequence of calls.
    """

    async def task(self, refs: list[str], cents: int) -> dict[str, Any]:
        for i, ref in enumerate(refs):
            if i:
                await self.sleep(1)  # the provider's rate limit, durably
            await self.step(f"charge-{ref}", self.charge, ref, cents)
        return {"charged": len(refs), "cents": cents}

    def charge(self, ref: str, cents: int) -> dict[str, Any]:
        CHARGES.append(ref)  # the provider dedupes on `ref`; we count calls
        if ref.endswith("-b") and self.job["error_count"] == 0:
            raise RuntimeError("provider returned 503")
        return {"ref": ref, "cents": cents}


async def test_the_pacing_releases_the_worker_and_charges_each_card_once(
    client, live_worker, unique_queue, batch_ref
):
    CHARGES.clear()
    await live_worker()

    refs = [f"{batch_ref}-a", f"{batch_ref}-b", f"{batch_ref}-c"]
    job_id = await client.enqueue(
        "tests.test_examples_doc.ChargeCards",
        queue=unique_queue,
        max_retries=3,
        initial_retry_delay=0,
        refs=refs,
        cents=1999,
    )

    # between calls the job is queued with a future run_after: it occupies
    # no worker and no connection while it waits out the rate limit
    for _ in range(80):
        row = await client.pool.fetchrow(
            "SELECT state, run_after > now() AS future FROM jorb WHERE id=$1", job_id
        )
        if row["state"] == "queued" and row["future"]:
            break
        await asyncio.sleep(0.1)
    assert row["state"] == "queued" and row["future"], dict(row)

    row = await wait_for_job_state(client.pool, job_id, ("finished",), timeout=40)
    assert row["result"] == {"charged": 3, "cents": 1999}
    assert row["error_count"] == 1  # the -b card's 503

    # -b was really re-sent; -a was NOT, because its step had committed
    assert [refs[0], refs[1], refs[1], refs[2]] == CHARGES


