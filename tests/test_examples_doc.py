async def test_a_schedule_creates_and_runs_its_job(
    client, live_worker, unique_queue, batch_ref
):
    """The whole path: define the schedule, let ``pj-scheduler`` fire it.

    The test backdates ``next_run`` and runs a single poll rather than
    waiting a real minute for the cron to come round; everything else — the
    deadline key, the admin_data, the created job — is what production does.
    """
    from pyjobby.admin_api import AdminAPI
    from pyjobby.scheduler import SchedulerWorker

    await live_worker()

    async with client.pool.acquire() as conn:
        schedule = await AdminAPI(conn).create_schedule(
            name=f"daily-revenue-{batch_ref}",
            job_class="tests.test_examples_doc.DailyRevenueReport",
            cron_expr="0 2 * * *",  # 02:00 every day...
            timezone="America/New_York",  # ...in Eastern wall-clock time
            queue=unique_queue,
            kwargs={"region": "emea"},
            max_concurrent_jobs=1,
            jitter_seconds=0,
            circuit_breaker_threshold=3,
            description="Daily revenue report at 2am Eastern",
        )
        assert schedule["next_run"] > utcnow()

        # force it due now instead of waiting for 02:00 Eastern
        await conn.execute(
            "UPDATE jorb_schedule SET next_run = now() - interval '1 minute' "
            "WHERE id = $1",
            schedule["id"],
        )

        worker = SchedulerWorker(conn, poll_interval=0.05)
        task = asyncio.create_task(worker.run())
        await asyncio.sleep(0.5)
        worker.stop()
        await asyncio.wait_for(task, timeout=5)

        after = await conn.fetchrow(
            "SELECT * FROM jorb_schedule WHERE id = $1", schedule["id"]
        )

    assert after["success_count"] == 1
    assert after["next_run"] > utcnow()  # advanced to the following 02:00

    job_id = await client.pool.fetchval(
        "SELECT id FROM jorb WHERE schedule_id = $1",
        schedule["id"],
    )
    row = await wait_for_job_state(client.pool, job_id, ("finished",), timeout=30)
    assert row["result"] == {
        "region": "emea",
        "schedule": f"daily-revenue-{batch_ref}",
    }
    # the deadline key is what makes a second scheduler instance a no-op
    assert row["deadline_key"].startswith(f"schedule:{schedule['id']}:")


