class Estimate(Job):
    """A short job whose caller wants the number back."""

    async def task(self, cents: int) -> dict[str, Any]:
        await self.set_event("progress", {"pct": 50})
        return {"total": cents * 2}


async def test_a_caller_can_wait_for_the_result(client, live_worker, unique_queue):
    await live_worker()

    handle = await client.enqueue_handle(
        "tests.test_examples_doc.Estimate", queue=unique_queue, cents=250
    )
    assert await handle.event("progress", timeout=15) == {"pct": 50}
    assert await handle.wait(timeout=20) == {"total": 500}
    assert await handle.status() == "finished"


class QuoteUnavailable(Job):
    """The other half of waiting: the job the caller was waiting on failed."""

    def task(self) -> None:
        raise ValueError("no price for that region")


async def test_a_dead_lettered_job_raises_at_the_waiter(
    client, live_worker, unique_queue
):
    await live_worker()

    handle = await client.enqueue_handle(
        "tests.test_examples_doc.QuoteUnavailable",
        queue=unique_queue,
        max_retries=1,
        initial_retry_delay=0,
    )

    with pytest.raises(JobFailedError, match="no price for that region"):
        await handle.wait(timeout=30)


