class ExtractSales(Job):
    """Stage one: pull the day's rows (here, generate them)."""

    async def task(self, day: str, count: int = 4) -> dict[str, Any]:
        rows = await self.step(
            "fetch", lambda: [{"sku": f"sku-{i}", "units": i + 1} for i in range(count)]
        )
        return {"day": day, "rows": rows}


class TransformSales(Job):
    """Stage two: reads stage one's result out of ``upstream_result``."""

    async def task(self, upstream_result: dict[str, Any]) -> dict[str, Any]:
        rows = upstream_result["rows"]
        return {
            "day": upstream_result["day"],
            "rows": [r for r in rows if r["units"] > 1],
        }


class LoadWarehouse(Job):
    """Stage three: the write, so it lands exactly once."""

    async def task(self, batch: str, upstream_result: dict[str, Any]) -> dict[str, Any]:
        return await self.transaction("load", self.load, batch, upstream_result["rows"])

    async def load(
        self, conn: Any, batch: str, rows: list[dict[str, Any]]
    ) -> dict[str, Any]:
        for row in rows:
            await conn.execute(
                "INSERT INTO example_row (batch, sku, units) VALUES ($1, $2, $3)",
                batch,
                row["sku"],
                row["units"],
            )
        return {"loaded": len(rows)}


async def test_the_etl_pipeline_runs_in_order_and_passes_results(
    client, live_worker, unique_queue, app_tables, batch_ref
):
    extract = await client.enqueue(
        "tests.test_examples_doc.ExtractSales",
        queue=unique_queue,
        day="2026-07-01",
        count=4,
    )
    transform = await client.enqueue(
        "tests.test_examples_doc.TransformSales",
        queue=unique_queue,
        waitfor_job=extract,
        use_result_from=extract,
    )
    load = await client.enqueue(
        "tests.test_examples_doc.LoadWarehouse",
        queue=unique_queue,
        waitfor_job=transform,
        use_result_from=transform,
        batch=batch_ref,
    )

    # the two downstream stages start out blocked, not queued
    blocked = await client.pool.fetch(
        "SELECT state FROM jorb WHERE id = ANY($1::bigint[])", [transform, load]
    )
    assert {r["state"] for r in blocked} == {"waiting"}

    await live_worker()

    row = await wait_for_job_state(client.pool, load, ("finished",), timeout=30)
    assert row["result"] == {"loaded": 3}  # sku-0 had 1 unit and was filtered

    rows = await client.pool.fetch(
        "SELECT sku FROM example_row WHERE batch = $1 ORDER BY sku", batch_ref
    )
    assert [r["sku"] for r in rows] == ["sku-1", "sku-2", "sku-3"]


